    private fun aTexto(m: CodigoQr.Matriz): List<String> =
        (0 until m.tamano).map { f -> (0 until m.tamano).joinToString("") { c -> if (m.oscuro(f, c)) "1" else "0" } }

    @Test
    fun igualQueLaLibreriaDeLaWebModuloAModulo() {
        for (caso in casos) {
            val m = CodigoQr.generar(caso.texto, caso.nivel, caso.mascara)
            assertEquals(caso.version, m.version, "versión de '${caso.texto.take(20)}'")
            assertEquals(caso.filas, aTexto(m), "matriz de '${caso.texto.take(20)}' (${caso.nivel}, máscara ${caso.mascara})")
        }
    }

    @Test
    fun mascaraAutomaticaDaUnQrValido() {
        val url = "https://www.saniape.com/unirse/0b6f7c1e-2a4d-4e8b-9c3f-5d1a2b3c4d5e"
        val m = CodigoQr.generar(url)
        assertEquals(5, m.version)
        assertEquals(37, m.tamano)
        assertTrue(m.mascara in 0..7)
        // Con la máscara que eligió, la matriz es la misma que fijándola a mano.
        assertEquals(aTexto(CodigoQr.generar(url, CodigoQr.Nivel.M, m.mascara)), aTexto(m))
    }

    @Test
    fun textoDemasiadoLargoFalla() {
        assertFailsWith<IllegalArgumentException> { CodigoQr.generar("x".repeat(3000), CodigoQr.Nivel.H) }
    }
